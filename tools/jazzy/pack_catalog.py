"""Move unchanged, cold factory and Grids data out of the linked app."""
import re
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2] / "rhythmer/firmware"
OUTPUT = Path(sys.argv[1])
OUTPUT.mkdir(parents=True, exist_ok=True)


def array(path, name):
    source = path.read_text()
    data = re.search(r"\b" + name + r"\[[^=]*=\s*\{(.*?)\};", source, re.S)[1]
    return [int(v) for v in re.findall(r"\d+", data)]


fp = ROOT / "jazzy/factory_projection.h"
offsets, blob = array(fp, "FP_AT"), bytes(array(fp, "FP_DATA"))
grids = bytes(array(ROOT / "six/drum_grids_map.h", "GRIDS_NODE"))
# Pack complete LZ4 blocks. Keep the final 256 bytes of each low sector blank
# for the boot ROM's record scan. DA/DB is JAZZY's unused post-index space.
first = max(v for v in offsets if v <= 8192)
second = max(v for v in offsets if v <= first + 3840)
parts = [blob[:first], blob[first:second], blob[second:] + grids]
addresses = (0xDA000, 0x94000, 0x95000)
caps = (8192, 3840, 3840)
assert all(len(p) <= c for p, c in zip(parts, caps))
# LXR shares the existing read-only catalog and the marker sector. Do not
# use the Break PCM sectors: custom sample uploads erase those sectors.
lxr = bytes(array(ROOT / "jazzy/lxr_factory.h", "LXR_SOURCE"))
marker = lxr[:0xEE0]
(OUTPUT / "93020.bin").write_bytes(marker)
offset = len(marker)
fragments = [(0x93020, offset)]
for i, (addr, cap) in enumerate(zip(addresses, caps)):
    start = len(parts[i])
    extra = lxr[offset:offset + cap - start]
    if extra:
        parts[i] += extra
        fragments.append((addr + start, len(extra)))
        offset += len(extra)
lxr_out = ROOT / "jazzy/lxr_assets.h"
lxr_out.write_text("/* Generated by pack_catalog.py. */\n#pragma once\n"
    f"#define LXR_MARKER_CRC 0x{zlib.crc32(marker):08x}u\n"
    f"#define LXR_MARKER_BYTES {len(marker)}u\n"
    "static const struct { uint32_t at; uint16_t end; } LXR_ASSETS[] = {\n"
    + "".join(f"    {{0x{addr:x}u, {sum(n for _, n in fragments[:i + 1])}u}},\n"
              for i, (addr, _) in enumerate(fragments))
    + "};\nstatic const uint8_t LXR_TAIL[] = {\n"
    + "".join("    " + ",".join(map(str, lxr[k:k + 24])) + ",\n"
              for k in range(offset, len(lxr), 24)) + "};\n")
print(f"LXR bank: {len(lxr)} bytes, {len(lxr)-offset} linked")
for addr, part in zip(addresses, parts):
    (OUTPUT / f"{addr:x}.bin").write_bytes(part)
out = ROOT / "jazzy/catalog_assets.h"
out.write_text(
    "/* Generated by pack_catalog.py. Raw XIP, unchanged factory and Grids bytes. */\n"
    "#pragma once\n"
    f"#define JCAT_FP_SPLIT1 {first}u\n"
    f"#define JCAT_FP_SPLIT2 {second}u\n"
    f"#define JCAT_GRIDS_AT 0x{addresses[-1] + len(blob) - second:x}u\n"
    "#if JAZZY_EXTERNAL_ASSETS\n"
    "static uint8_t jazzy_catalog_valid;\n"
    "static const struct { uint32_t at, size, crc; } JCAT_PARTS[] = {\n"
    + "".join(f"    {{0x{a:x}u, {len(p)}u, 0x{zlib.crc32(p):08x}u}},\n" for a, p in zip(addresses, parts))
    + "};\n#else\n#define jazzy_catalog_valid 1\n#endif\n"
)
print("Factory and Grids moved from linked app:", [len(p) for p in parts])
