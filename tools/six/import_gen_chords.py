#!/usr/bin/env python3
"""Select JR TREK/SHLD progressions for four-voice embedded GEN; no MIDI/JS runtime."""
import argparse,json,hashlib,shutil
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
ap=argparse.ArgumentParser();ap.add_argument('--trek',type=Path,required=True);a=ap.parse_args()
src=a.trek/'Shared/ChordSets.json';rows={r['id']:r for r in json.loads(src.read_text())}
# Curated diatonic reduction: omit fifth/root before the identifying 7/9/13.
selected=[
 ('JR_VELVET','jr-velvet','major',['Q_R9','Q_R9','Q_R9','Q_R13']),
 ('JR_MIDNIGHT','jr-midnight-call','major',['Q_9','Q_R13','Q_R9','Q_R9']),
 ('JR_SILHOUETTE','jr-silhouette','major',['Q_7','Q_7','Q_9','Q_11']),
 ('JR_CLOSE','jr-close-to-you','major',['Q_9','Q_S79','Q_9','Q_9']),
 ('JR_BLUE','jr-blue-satin','minor',['Q_9','Q_9','Q_R13','Q_9']),
 ('JR_NIGHT','jr-night-promise','minor',['Q_9','Q_9','Q_7','Q_S79']),
 ('SH_PLAY','shld-017093372a45','major',['Q_7','Q_7','Q_ADD9','Q_7']),
 ('SH_TRIUMPH','shld-b76010ec6173','major',['Q_7','Q_ADD9','Q_7']),
 ('SH_RELAX','shld-41ffd06b6147','major',['Q_TRI','Q_TRI','Q_6','Q_ADD9']),
]
report={'sourceSha256':hashlib.sha256(src.read_bytes()).hexdigest(),'adaptation':'Four voices; rootless 9/13 share bass root. Scale-aware quality validation remains active. No copied recordings.','rows':[]}
h='/* Generated by tools/six/import_gen_chords.py; JR TREK originals + SHLD (MIT). */\n'
for name,ident,mode,qualities in selected:
 row=rows[ident];scale=[0,2,4,5,7,9,11] if mode=='major' else [0,2,3,5,7,8,10]
 deg=[scale.index(c['root']) for c in row['chords']];assert len(deg)==len(qualities)
 h+=' [PR_'+name+']={'+str(len(deg))+',{'+','.join(map(str,deg))+'},{'+','.join(qualities)+'}},\n'
 report['rows'].append({'key':name,'mode':mode,'source':row,'degrees':deg,'qualities':qualities})
(ROOT/'rhythmer/firmware/src/gen_jr_progressions.h').write_text(h)
(ROOT/'rhythmer/firmware/data/genres/jr-chords.json').write_text(json.dumps(report,indent=2)+'\n')
shutil.copyfile(a.trek/'ThirdParty/SHLD/LICENSE',ROOT/'rhythmer/LICENSES/MIT-SHLD.txt')
print('Imported',len(selected),'progressions with source rows and MIT notice.')
